#!/usr/bin/env python3
"""Refresh the checked-in public catalog sample from a read-only PostgreSQL source.

Uses libpq's PGHOST/PGPORT/PGDATABASE/PGUSER/PGPASSWORD/PGSSLMODE settings.
Only the explicit catalog table allowlist is exported. No source data is changed.
"""

import datetime
import gzip
import hashlib
import json
import os
from pathlib import Path
import subprocess

DIRECTORY = Path(__file__).resolve().parent
ARTISTS = [1, 4, 9, 287, 292]  # Lotus, Phish, Grateful Dead, Guerilla Toss, Trey.
CATALOG = {
    "upstream_sources": "true",
    "artists": "id IN (SELECT id FROM picked_artists)",
    "features": "artist_id IN (SELECT id FROM picked_artists)",
    "artists_upstream_sources": "artist_id IN (SELECT id FROM picked_artists)",
    "eras": "artist_id IN (SELECT id FROM picked_artists)",
    "tours": "id IN (SELECT tour_id FROM picked_shows UNION SELECT tour_id FROM picked_setlists)",
    "venues": "id IN (SELECT venue_id FROM picked_shows UNION SELECT venue_id FROM picked_sources UNION SELECT venue_id FROM picked_setlists)",
    "years": "id IN (SELECT year_id FROM picked_shows)",
    "shows": "id IN (SELECT id FROM picked_shows)",
    "sources": "id IN (SELECT id FROM picked_sources)",
    "source_sets": "source_id IN (SELECT id FROM picked_sources)",
    "source_tracks": "source_id IN (SELECT id FROM picked_sources)",
    "source_reviews": "id IN (SELECT id FROM picked_reviews)",
    "links": "source_id IN (SELECT id FROM picked_sources)",
    "setlist_shows": "id IN (SELECT id FROM picked_setlists)",
    "setlist_songs": "id IN (SELECT played_setlist_song_id FROM setlist_songs_plays WHERE played_setlist_show_id IN (SELECT id FROM picked_setlists))",
    "setlist_songs_plays": "played_setlist_show_id IN (SELECT id FROM picked_setlists)",
    "versioninfo": "true",
}
DERIVED_TABLES = ["show_source_information", "source_review_counts", "venue_show_counts"]

# Each artist has a small, playable sample. Source and review limits keep an
# unusually popular recording from making a future refresh unexpectedly large.
SELECTION = f"""
WITH picked_artists AS (SELECT id FROM artists WHERE id IN ({','.join(map(str, ARTISTS))})),
picked_shows AS (
    SELECT s.* FROM picked_artists a CROSS JOIN LATERAL (
        SELECT * FROM shows WHERE artist_id = a.id ORDER BY display_date DESC LIMIT 8
    ) s
), picked_sources AS (
    SELECT src.* FROM picked_shows sh CROSS JOIN LATERAL (
        SELECT * FROM sources WHERE show_id = sh.id
        ORDER BY avg_rating_weighted DESC NULLS LAST, id LIMIT 2
    ) src
), picked_setlists AS (
    SELECT ss.* FROM setlist_shows ss JOIN picked_shows sh
        ON ss.artist_id = sh.artist_id AND ss.date = sh.date
), picked_reviews AS (
    SELECT r.* FROM picked_sources src CROSS JOIN LATERAL (
        SELECT * FROM source_reviews WHERE source_id = src.id ORDER BY id LIMIT 10
    ) r
)
"""


def run(command):
    return subprocess.check_output(command, env=SOURCE_ENV)


SOURCE_ENV = dict(os.environ)
SOURCE_ENV["PGOPTIONS"] = "-c default_transaction_read_only=on -c statement_timeout=30000"


def main():
    table_args = [f"--table=public.{table}" for table in [*CATALOG, *DERIVED_TABLES]]
    schema = run(["pg_dump", "--schema-only", "--no-owner", "--no-privileges", *table_args]).decode()
    # pg_dump 17+ adds psql-only random restriction keys. The schema also serves
    # the integration tests through Npgsql, so keep it executable as ordinary SQL.
    schema = "\n".join(line for line in schema.splitlines() if not line.startswith("\\"))
    schema += "\n" + (DIRECTORY / "analytics.sql").read_text()

    rows = {}
    chunks = [b"-- Public catalog sample. Generated by export-seed.py.\nSET search_path = public;\n"]
    for table, predicate in CATALOG.items():
        query = f"{SELECTION} SELECT * FROM public.{table} WHERE {predicate} ORDER BY 1, 2"
        data = run(["psql", "-X", "-q", "-v", "ON_ERROR_STOP=1", "-c", f"COPY ({query}) TO STDOUT"])
        rows[table] = len(data.splitlines())
        chunks.extend([f"COPY public.{table} FROM stdin;\n".encode(), data, b"\\.\n\n"])

    chunks.append((DIRECTORY / "finalize.sql").read_bytes())
    compressed = gzip.compress(b"".join(chunks), mtime=0)
    if len(compressed) >= 5_000_000:
        raise SystemExit("Seed exceeds 5 MB. Reduce the selection before replacing the checked-in sample.")

    (DIRECTORY / "schema.sql").write_text(schema)
    (DIRECTORY / "data.sql.gz").write_bytes(compressed)
    manifest = {
        "exported_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "artist_ids": ARTISTS,
        "shows_per_artist": 8,
        "sources_per_show": 2,
        "reviews_per_source": 10,
        "rows": rows,
        "compressed_bytes": len(compressed),
        "sha256": hashlib.sha256(compressed).hexdigest(),
    }
    (DIRECTORY / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
